"""Every installed package is one we chose (task-236; ADR-189).

`backend/scripts/check_installed.py` compares what is installed with what is
locked — the Python venv with `requirements.txt` + `requirements-dev.txt`, and
`frontend/node_modules` with `package-lock.json` — and fails on anything that
is installed but not locked, locked at another version, or locked and
missing. A CVE scanner answers "is a known package known-bad"; this answers
"is every installed package one we chose", which is how `httpx2` stayed in the
venv for three months. A name close to a locked one is named as a likely
typo or squat.
"""
import json
from pathlib import Path

import pytest

from scripts import check_installed as check

LOCK = """\
#
# This file is autogenerated by pip-compile with Python 3.14
#
httpx==0.28.1 \\
    --hash=sha256:aaa
    # via -r requirements.in
Jinja2==3.1.6 \\
    --hash=sha256:bbb
typing_extensions==4.15.0 \\
    --hash=sha256:ccc
"""


def test_a_lock_is_read_as_normalised_names_and_versions(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text(LOCK)
    assert check.read_python_lock(path) == {"httpx": "0.28.1", "jinja2": "3.1.6", "typing-extensions": "4.15.0"}


class TestPython:
    LOCKED = {"httpx": "0.28.1", "jinja2": "3.1.6", "pip": "26.2.1"}

    def test_exactly_the_lock_passes(self):
        assert check.compare("python", self.LOCKED, dict(self.LOCKED)) == []

    def test_a_package_nobody_chose_fails_and_a_near_name_is_called_out(self):
        installed = {**self.LOCKED, "httpx2": "2.5.0", "truststore": "0.10.4"}
        problems = check.compare("python", self.LOCKED, installed)
        assert [p.kind for p in problems] == ["not locked", "not locked"]
        httpx2 = next(p for p in problems if p.name == "httpx2")
        assert "looks like httpx" in httpx2.describe()
        truststore = next(p for p in problems if p.name == "truststore")
        assert "looks like" not in truststore.describe()

    def test_another_version_fails(self):
        problems = check.compare("python", self.LOCKED, {**self.LOCKED, "pip": "26.1.1"})
        assert [(p.kind, p.name, p.installed, p.locked) for p in problems] == [
            ("other version", "pip", "26.1.1", "26.2.1")]

    def test_a_locked_package_that_is_missing_fails(self):
        installed = dict(self.LOCKED)
        del installed["jinja2"]
        assert [(p.kind, p.name) for p in check.compare("python", self.LOCKED, installed)] == [("missing", "jinja2")]


def _npm(tmp_path, lock_packages: dict, installed_packages: dict) -> Path:
    root = tmp_path / "frontend"
    (root / "node_modules").mkdir(parents=True)
    (root / "package-lock.json").write_text(json.dumps({"packages": {"": {"name": "client"}, **lock_packages}}))
    (root / "node_modules" / ".package-lock.json").write_text(json.dumps({"packages": installed_packages}))
    return root


class TestNpm:
    REACT = {"node_modules/react": {"version": "19.3.0"}}
    ANDROID = {"node_modules/@rolldown/binding-android-arm64": {"version": "1.0.0", "optional": True}}

    def test_an_optional_build_for_another_platform_may_be_absent(self, tmp_path):
        root = _npm(tmp_path, {**self.REACT, **self.ANDROID}, dict(self.REACT))
        locked, installed = check.read_npm(root)
        assert check.compare("npm", locked, installed) == []

    def test_a_package_in_node_modules_that_the_lock_does_not_hold_fails(self, tmp_path):
        root = _npm(tmp_path, dict(self.REACT), {**self.REACT, "node_modules/reactt": {"version": "1.0.0"}})
        problems = check.compare("npm", *check.read_npm(root))
        assert [(p.kind, p.name) for p in problems] == [("not locked", "reactt")]
        assert "looks like react" in problems[0].describe()

    def test_a_different_version_and_a_missing_required_package_fail(self, tmp_path):
        root = _npm(tmp_path, {**self.REACT, "node_modules/vite": {"version": "8.3.0"}},
                    {"node_modules/react": {"version": "19.2.0"}})
        problems = check.compare("npm", *check.read_npm(root))
        assert sorted((p.kind, p.name) for p in problems) == [("missing", "vite"), ("other version", "react")]

    def test_a_nested_copy_is_named_by_its_full_path(self, tmp_path):
        nested = {"node_modules/a/node_modules/b": {"version": "2.0.0"}}
        root = _npm(tmp_path, dict(self.REACT), {**self.REACT, **nested})
        [problem] = check.compare("npm", *check.read_npm(root))
        assert problem.name == "a/node_modules/b"


def test_a_lock_that_disagrees_with_package_json_fails(tmp_path):
    """The lock's root entry records what package.json asked for; a dependency
    in one and not the other, or at another range, means one changed without
    the other."""
    root = tmp_path / "frontend"
    root.mkdir()
    (root / "package.json").write_text(json.dumps({
        "dependencies": {"react": "^19.3.0"}, "devDependencies": {"vite": "^8.3.0"}}))
    (root / "package-lock.json").write_text(json.dumps({"packages": {"": {
        "dependencies": {"react": "^19.2.0", "left-pad": "^1.0.0"}, "devDependencies": {"vite": "^8.3.0"}}}}))
    problems = check.package_json_against_lock(root)
    assert sorted((p.kind, p.name) for p in problems) == [("not in package.json", "left-pad"), ("other range", "react")]
    assert "left-pad" in problems[0].describe() or "left-pad" in problems[1].describe()


def test_the_command_fails_on_a_problem_and_says_what_it_found(tmp_path, capsys, monkeypatch):
    (tmp_path / "requirements.txt").write_text(LOCK)
    (tmp_path / "requirements-dev.txt").write_text("")
    monkeypatch.setattr(check, "installed_python", lambda python: {
        "httpx": "0.28.1", "jinja2": "3.1.6", "typing-extensions": "4.15.0", "httpx2": "2.5.0"})
    code = check.main(["--backend", str(tmp_path), "--frontend", str(_npm(tmp_path, {}, {}))])
    out = capsys.readouterr().out
    assert code == 1
    assert "python: httpx2 2.5.0 is installed but not locked" in out and "looks like httpx" in out


def test_the_real_install_matches_its_locks():
    """The repository's own venv and node_modules, as they are: what the
    command checks when someone runs it. Skipped where either is not installed."""
    backend = Path(check.__file__).resolve().parents[1]
    frontend = backend.parent / "frontend"
    if not (backend / "venv").exists() or not (frontend / "node_modules").exists():
        pytest.skip("no local install to check")
    assert check.main(["--backend", str(backend), "--frontend", str(frontend)]) == 0
